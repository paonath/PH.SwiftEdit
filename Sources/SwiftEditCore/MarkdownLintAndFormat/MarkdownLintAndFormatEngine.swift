import Foundation
import Markdown

/// Canonical rule identifiers emitted by `MarkdownLintAndFormatEngine.lint` (`AR-011`, `BC-004`, `SEC-004`).
public enum MarkdownLintRuleID: String, Codable, Sendable {
    case missingHeadingSpace
    case emptyLinkTarget
    case unsafeLinkScheme
    case unbalancedFencedCodeBlock
}

/// Immutable 1-based line diagnostic emitted during offline Markdown AST and structural linting (`BC-004`).
public struct MarkdownLintDiagnostic: Equatable, Sendable {
    public let rule: MarkdownLintRuleID
    public let line: Int
    public let message: String

    public init(rule: MarkdownLintRuleID, line: Int, message: String) {
        self.rule = rule
        self.line = line
        self.message = message
    }
}

/// Revision-tagged Markdown lint output associated with an immutable `DocumentSnapshot` (`BC-004`, `BC-006`).
public struct MarkdownLintResult: Equatable, Sendable {
    public let documentID: DocumentID
    public let revision: BufferRevision
    public let diagnostics: [MarkdownLintDiagnostic]

    public init(documentID: DocumentID, revision: BufferRevision, diagnostics: [MarkdownLintDiagnostic]) {
        self.documentID = documentID
        self.revision = revision
        self.diagnostics = diagnostics
    }
}

/// Revision-tagged batch of `TextEdit` replacements generated by `formatDocument` or `formatSection` (`BC-004`).
public struct MarkdownFormatBatch: Equatable, Sendable {
    public let documentID: DocumentID
    public let revision: BufferRevision
    public let edits: [TextEdit]

    public init(documentID: DocumentID, revision: BufferRevision, edits: [TextEdit]) {
        self.documentID = documentID
        self.revision = revision
        self.edits = edits
    }
}

/// Pure, 100% offline CommonMark / GitHub Flavored Markdown AST linter and formatter backed by `swiftlang/swift-markdown` (`AR-011`, `AR-013`, `BC-004`, `BC-011`, `SEC-004`, `SEC-012`).
///
/// Security & complexity invariants:
/// - Rejects `isBinaryReadOnly` (`.binarySnapshot`) and `isDegradedPlainText` (`.degradedPlainTextSnapshot`) inputs before AST allocation.
/// - Enforces an iterative heap-stack AST nesting ceiling of `maxASTDepth` (`128`) to prevent stack exhaustion.
/// - Enforces a cooperative `deadlineMilliseconds` (`250 ms`) budget via `ElapsedTimeProviding`.
/// - Flags any explicit URI scheme outside `allowedLinkSchemes` (`https`, `http`, `mailto`) as `.unsafeLinkScheme`.
public enum MarkdownLintAndFormatEngine {
    /// Maximum CommonMark / GFM AST nesting depth permitted before returning `.astDepthExceeded(maxDepth: 128)` (`BC-011`, `SEC-012`).
    public static let maxASTDepth: Int = 128
    /// Cooperative wall-clock budget in milliseconds enforced across AST parsing and line scanning (`AR-013`, `BC-011`).
    public static let deadlineMilliseconds: Int = 250
    /// Explicit URI schemes permitted in Markdown links and images without triggering `.unsafeLinkScheme` (`SEC-004`, `SEC-012`).
    public static let allowedLinkSchemes: Set<String> = ["https", "http", "mailto"]

    /// Parses `snapshot` via `swift-markdown`, enforces `128`-level AST depth and `250 ms` clock bounds, and emits sorted `MarkdownLintDiagnostic` findings including `.unsafeLinkScheme`.
    public static func lint(
        snapshot: DocumentSnapshot,
        clock: any ElapsedTimeProviding = ContinuousClockElapsedTimer()
    ) -> EngineEvaluationOutcome<MarkdownLintResult> {
        let document: Document
        switch parseAdmissibleAST(snapshot: snapshot, clock: clock) {
        case .success(let parsed):
            document = parsed
        case .failure(let reason):
            return .degradedOrTimedOut(reason)
        }

        var walker = MarkdownASTLintWalker()
        walker.visit(document)

        var diagnostics = walker.diagnostics
        var fenceTracker = FencedCodeBlockTracker()

        for line in splitLinesUTF16(in: snapshot.text) {
            if clock.elapsedMilliseconds() > deadlineMilliseconds {
                return .degradedOrTimedOut(.deadlineExceeded(limitMilliseconds: deadlineMilliseconds))
            }
            if fenceTracker.consume(lineContent: line.content, lineNumber: line.lineNumber) {
                continue
            }
            if hasMissingHeadingSpace(line.content) {
                diagnostics.append(MarkdownLintDiagnostic(
                    rule: .missingHeadingSpace,
                    line: line.lineNumber,
                    message: "ATX heading requires a space after '#' markers"
                ))
            }
        }

        if let unclosedLine = fenceTracker.unclosedOpeningLine {
            diagnostics.append(MarkdownLintDiagnostic(
                rule: .unbalancedFencedCodeBlock,
                line: unclosedLine,
                message: "Opening code fence is not closed"
            ))
        }

        diagnostics.sort { lhs, rhs in
            if lhs.line != rhs.line { return lhs.line < rhs.line }
            return lhs.rule.rawValue < rhs.rule.rawValue
        }

        return .completed(MarkdownLintResult(
            documentID: snapshot.id,
            revision: snapshot.revision,
            diagnostics: diagnostics
        ))
    }

    /// Generates a whole-document `MarkdownFormatBatch` normalizing headings, list markers, and trailing spaces outside fenced code blocks while enforcing `128`-level AST depth and `250 ms` deadline bounds.
    public static func formatDocument(
        snapshot: DocumentSnapshot,
        clock: any ElapsedTimeProviding = ContinuousClockElapsedTimer()
    ) -> EngineEvaluationOutcome<MarkdownFormatBatch> {
        evaluateFormat(snapshot: snapshot, targetRange: nil, clock: clock)
    }

    /// Generates a section-scoped `MarkdownFormatBatch` restricted to non-fenced lines intersecting `range` while enforcing `128`-level AST depth and `250 ms` deadline bounds.
    /// - Throws: `DomainError.invalidTextRange` when `range` lies outside `snapshot.text`.
    public static func formatSection(
        snapshot: DocumentSnapshot,
        range: TextRange,
        clock: any ElapsedTimeProviding = ContinuousClockElapsedTimer()
    ) throws -> EngineEvaluationOutcome<MarkdownFormatBatch> {
        try validateRange(range, in: snapshot.text)
        return evaluateFormat(snapshot: snapshot, targetRange: range, clock: clock)
    }

    private enum AdmissibleASTResult {
        case success(Document)
        case failure(DegradedEvaluationReason)
    }

    private static func parseAdmissibleAST(
        snapshot: DocumentSnapshot,
        clock: any ElapsedTimeProviding
    ) -> AdmissibleASTResult {
        if snapshot.isBinaryReadOnly {
            return .failure(.binarySnapshot)
        }
        if snapshot.isDegradedPlainText {
            return .failure(.degradedPlainTextSnapshot)
        }
        if clock.elapsedMilliseconds() > deadlineMilliseconds {
            return .failure(.deadlineExceeded(limitMilliseconds: deadlineMilliseconds))
        }

        let document = Document(parsing: snapshot.text)
        if exceedsMaxASTDepth(document, maxDepth: maxASTDepth) {
            return .failure(.astDepthExceeded(maxDepth: maxASTDepth))
        }
        if clock.elapsedMilliseconds() > deadlineMilliseconds {
            return .failure(.deadlineExceeded(limitMilliseconds: deadlineMilliseconds))
        }
        return .success(document)
    }

    private static func evaluateFormat(
        snapshot: DocumentSnapshot,
        targetRange: TextRange?,
        clock: any ElapsedTimeProviding
    ) -> EngineEvaluationOutcome<MarkdownFormatBatch> {
        if case .failure(let reason) = parseAdmissibleAST(snapshot: snapshot, clock: clock) {
            return .degradedOrTimedOut(reason)
        }

        var edits: [TextEdit] = []
        var fenceTracker = FencedCodeBlockTracker()

        for line in splitLinesUTF16(in: snapshot.text) {
            if clock.elapsedMilliseconds() > deadlineMilliseconds {
                return .degradedOrTimedOut(.deadlineExceeded(limitMilliseconds: deadlineMilliseconds))
            }
            if fenceTracker.consume(lineContent: line.content, lineNumber: line.lineNumber) {
                continue
            }
            if let selection = targetRange, !lineIntersects(line: line, selection: selection) {
                continue
            }
            let formatted = canonicalizeMarkdownLine(line.content)
            if formatted != line.content {
                edits.append(TextEdit(
                    range: TextRange(location: line.utf16Location, length: line.utf16Length),
                    replacement: formatted
                ))
            }
        }

        return .completed(MarkdownFormatBatch(
            documentID: snapshot.id,
            revision: snapshot.revision,
            edits: edits
        ))
    }

    private static func exceedsMaxASTDepth(_ root: any Markup, maxDepth: Int) -> Bool {
        var stack: [(node: any Markup, depth: Int)] = [(root, 0)]
        while let current = stack.popLast() {
            if current.depth > maxDepth {
                return true
            }
            for child in current.node.children {
                stack.append((child, current.depth + 1))
            }
        }
        return false
    }

    private enum URISchemeSecurityPolicy {
        static func disallowedScheme(in target: String) -> String? {
            let compacted = String(target.unicodeScalars.filter { $0.value > 0x20 })
            guard !compacted.hasPrefix("#"),
                  !compacted.hasPrefix("/"),
                  !compacted.hasPrefix("./"),
                  !compacted.hasPrefix("../") else {
                return nil
            }
            let boundaryIndex = compacted.firstIndex { $0 == ":" || $0 == "/" || $0 == "?" || $0 == "#" }
            guard let index = boundaryIndex, compacted[index] == ":" else {
                return nil
            }
            let scheme = compacted[..<index].lowercased()
            guard !MarkdownLintAndFormatEngine.allowedLinkSchemes.contains(scheme) else {
                return nil
            }
            return scheme
        }
    }

    private struct LineSlice {
        let lineNumber: Int
        let utf16Location: Int
        let utf16Length: Int
        let content: String
    }

    private struct FencedCodeBlockTracker {
        private var activeFence: (marker: Character, count: Int, line: Int)?

        var unclosedOpeningLine: Int? { activeFence?.line }

        mutating func consume(lineContent: String, lineNumber: Int) -> Bool {
            if let current = activeFence {
                if Self.isClosingFence(lineContent, matching: current.marker, minCount: current.count) {
                    activeFence = nil
                }
                return true
            }
            if let opened = Self.parseOpeningFence(lineContent, lineNumber: lineNumber) {
                activeFence = opened
                return true
            }
            return false
        }

        private static func parseOpeningFence(_ line: String, lineNumber: Int) -> (marker: Character, count: Int, line: Int)? {
            let leadingSpaces = line.prefix(while: { $0 == " " }).count
            guard leadingSpaces <= 3 else { return nil }
            let rest = line.dropFirst(leadingSpaces)
            guard let first = rest.first, first == "`" || first == "~" else { return nil }
            let count = rest.prefix(while: { $0 == first }).count
            guard count >= 3 else { return nil }
            let infoString = rest.dropFirst(count)
            if first == "`" && infoString.contains("`") {
                return nil
            }
            return (first, count, lineNumber)
        }

        private static func isClosingFence(_ line: String, matching marker: Character, minCount: Int) -> Bool {
            let leadingSpaces = line.prefix(while: { $0 == " " }).count
            guard leadingSpaces <= 3 else { return false }
            let rest = line.dropFirst(leadingSpaces)
            let count = rest.prefix(while: { $0 == marker }).count
            guard count >= minCount else { return false }
            return rest.dropFirst(count).allSatisfy { $0 == " " || $0 == "\t" }
        }
    }

    private struct MarkdownASTLintWalker: MarkupWalker {
        var diagnostics: [MarkdownLintDiagnostic] = []

        mutating func visitLink(_ link: Link) {
            inspectDestination(link.destination, line: link.range?.lowerBound.line ?? 1)
            descendInto(link)
        }

        mutating func visitImage(_ image: Image) {
            inspectDestination(image.source, line: image.range?.lowerBound.line ?? 1)
            descendInto(image)
        }

        private mutating func inspectDestination(_ rawTarget: String?, line: Int) {
            let trimmed = (rawTarget ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
            if trimmed.isEmpty {
                diagnostics.append(MarkdownLintDiagnostic(
                    rule: .emptyLinkTarget,
                    line: line,
                    message: "Markdown link or image has an empty destination"
                ))
                return
            }

            if let disallowedScheme = URISchemeSecurityPolicy.disallowedScheme(in: trimmed) {
                diagnostics.append(MarkdownLintDiagnostic(
                    rule: .unsafeLinkScheme,
                    line: line,
                    message: "Disallowed URI scheme '\(disallowedScheme)' in Markdown link or image"
                ))
            }
        }
    }

    private static func validateRange(_ range: TextRange, in text: String) throws {
        guard range.location >= 0,
              range.length >= 0,
              range.upperBound <= text.utf16.count,
              Range(NSRange(location: range.location, length: range.length), in: text) != nil else {
            throw DomainError.invalidTextRange(range)
        }
    }

    private static func lineIntersects(line: LineSlice, selection: TextRange) -> Bool {
        let lineStart = line.utf16Location
        let lineEnd = line.utf16Location + line.utf16Length
        if selection.length == 0 {
            return selection.location >= lineStart && selection.location <= lineEnd
        }
        if line.utf16Length == 0 {
            return lineStart >= selection.location && lineStart < selection.upperBound
        }
        return max(lineStart, selection.location) < min(lineEnd, selection.upperBound)
    }

    private static func canonicalizeMarkdownLine(_ line: String) -> String {
        let leadingSpacesCount = line.prefix(while: { $0 == " " }).count
        let afterLeading = line.dropFirst(leadingSpacesCount)

        if leadingSpacesCount <= 3, afterLeading.first == "#" {
            let hashCount = afterLeading.prefix(while: { $0 == "#" }).count
            if (1...6).contains(hashCount) {
                let remainder = afterLeading.dropFirst(hashCount)
                let trimmedRemainder = trimTrailingHorizontalWhitespace(String(remainder)).drop(while: { $0 == " " || $0 == "\t" })
                if !trimmedRemainder.isEmpty {
                    let prefixIndent = String(repeating: " ", count: leadingSpacesCount)
                    return "\(prefixIndent)\(String(repeating: "#", count: hashCount)) \(trimmedRemainder)"
                }
            }
        }

        if let marker = afterLeading.first, (marker == "*" || marker == "+" || marker == "-"), !isThematicBreak(afterLeading) {
            let afterMarker = afterLeading.dropFirst()
            if let firstAfter = afterMarker.first, firstAfter == " " || firstAfter == "\t" {
                let itemContent = trimTrailingHorizontalWhitespace(String(afterMarker.drop(while: { $0 == " " || $0 == "\t" })))
                let prefixIndent = String(repeating: " ", count: leadingSpacesCount)
                if itemContent.isEmpty {
                    return "\(prefixIndent)-"
                }
                return "\(prefixIndent)- \(itemContent)"
            }
        }

        return trimTrailingHorizontalWhitespace(line)
    }

    private static func isThematicBreak(_ trimmedLeading: Substring) -> Bool {
        guard let marker = trimmedLeading.first, marker == "*" || marker == "-" || marker == "_" else {
            return false
        }
        var markerCount = 0
        for ch in trimmedLeading {
            if ch == marker {
                markerCount += 1
            } else if ch != " " && ch != "\t" {
                return false
            }
        }
        return markerCount >= 3
    }

    private static func hasMissingHeadingSpace(_ line: String) -> Bool {
        let leadingSpaces = line.prefix(while: { $0 == " " }).count
        guard leadingSpaces <= 3 else { return false }
        let rest = line.dropFirst(leadingSpaces)
        let hashCount = rest.prefix(while: { $0 == "#" }).count
        guard (1...6).contains(hashCount) else { return false }
        guard let nextChar = rest.dropFirst(hashCount).first else { return false }
        return nextChar != " " && nextChar != "\t"
    }

    private static func trimTrailingHorizontalWhitespace(_ string: String) -> String {
        var end = string.endIndex
        while end > string.startIndex {
            let prev = string.index(before: end)
            if string[prev] == " " || string[prev] == "\t" {
                end = prev
            } else {
                break
            }
        }
        return String(string[..<end])
    }

    private static func splitLinesUTF16(in text: String) -> [LineSlice] {
        var slices: [LineSlice] = []
        var lineNumber = 1
        var lineStartIndex = text.startIndex
        var lineStartUTF16 = 0
        var currentIndex = text.startIndex
        var currentUTF16 = 0

        while currentIndex < text.endIndex {
            let ch = text[currentIndex]
            let chUTF16 = ch.utf16.count
            if ch == "\n" || ch == "\r" || ch == "\r\n" {
                let content = String(text[lineStartIndex..<currentIndex])
                slices.append(LineSlice(
                    lineNumber: lineNumber,
                    utf16Location: lineStartUTF16,
                    utf16Length: currentUTF16 - lineStartUTF16,
                    content: content
                ))
                lineNumber += 1
                currentIndex = text.index(after: currentIndex)
                currentUTF16 += chUTF16
                lineStartIndex = currentIndex
                lineStartUTF16 = currentUTF16
            } else {
                currentIndex = text.index(after: currentIndex)
                currentUTF16 += chUTF16
            }
        }

        let tailContent = String(text[lineStartIndex..<text.endIndex])
        slices.append(LineSlice(
            lineNumber: lineNumber,
            utf16Location: lineStartUTF16,
            utf16Length: currentUTF16 - lineStartUTF16,
            content: tailContent
        ))
        return slices
    }
}
